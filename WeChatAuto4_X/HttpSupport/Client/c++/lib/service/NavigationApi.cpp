#include "NavigationApi.h"

using namespace Tiny;



        Response<
            String
        >
        NavigationApi::
        navigationClose(
            
            std::string clientId
            , 
            
            SwitchNavigationRequest switchNavigationRequest
            
        )
        {
            std::string url = basepath + "/api/v1/clients/{clientId}/navigation/close"; //clientId 


            // Headers  | 

            // Query    | 

            // Form     | 
            addHeader("Content-Type", "application/json");



                std::string s_clientId("{");
                s_clientId.append("clientId");
                s_clientId.append("}");

                int pos = url.find(s_clientId);

                url.erase(pos, s_clientId.length());
                url.insert(pos, stringify(clientId));


            std::string payload = "";
            // Send Request
            // METHOD | POST
            // Body     | switchNavigationRequest



            payload = switchNavigationRequest.toJson().dump();

            int httpCode = sendRequest(url, "POST", reinterpret_cast<uint8_t*>(&payload[0]), payload.length());

            // Handle Request
            String output = getResponseBody();
            std::string output_string = output.c_str();


            Response<String> response(output, httpCode);
            return response;
        }

